# %-10s는 10칸 왼쪽 정렬, %5d는 5칸 오른쪽 정렬
print("%-10s : %5d원" % ("사과", 1500))
print("%-10s : %5d원" % ("바나나", 2500))
print("%-10s : %5d원" % ("애플망고", 12000))

print(f"{'사과':<10} : {1500:>5,}원")
print(f"{'바나나':<10} : {2500:>5,}원")
print(f"{'애플망고':<10} : {12000:>5,}원")